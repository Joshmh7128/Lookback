"""Writes the tiny model the C# tests check inference and calibration against.

    python -m lookback_ml.make_fixture

Trains on a small synthetic set, exports it, and records for a handful of
feature vectors (some with missing values, some for games or profiles the
model does or does not cover) the raw probability from ONNX Runtime and the
calibrated probability. ``tests/Lookback.Scoring.Tests`` loads the same files
and must produce the same numbers. Regenerate after changing training,
export or calibration, and commit the result.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from .calibration import Platt, lookup
from .data import load_dataset
from .schema import load_schema
from .synth import generate, write as write_rows
from .train import REPO, Options, impute, onnx_predict, train, write

FIXTURE = REPO / "tests" / "Lookback.Scoring.Tests" / "Fixtures"
PROFILES = ["synth-a.mode1", "synth-a.mode2", "synth-a.unlisted", "synth-a", "synth-b", "synth-b.mode9", "other-game"]


def build(scratch: Path, out: Path) -> dict:
    schema = load_schema()
    write_rows(generate(schema, games=2, sessions_per_game=4, candidates_per_session=12, seed=7), scratch)
    ds = load_dataset(scratch, schema)
    result = train(ds, Options(min_rows=20, min_sessions=3, min_per_class=3, min_game_rows=10, folds=4, c_grid=(0.1, 1.0)))
    write(result, out / "model")
    (out / "model" / "report.json").unlink()
    (out / "model" / "report.md").unlink()

    rng = np.random.default_rng(11)
    probe = generate(schema, games=1, sessions_per_game=1, candidates_per_session=len(PROFILES), seed=99, missing=0.2, retractions=0)
    m = result.manifest
    means = np.array(m["featureMeans"])
    glob = Platt(**m["calibration"]["global"])
    table = {k: Platt(**v) for k, v in m["calibration"]["profiles"].items()}
    cases = []
    for i, row in enumerate(probe):
        x = np.array([np.nan if v is None else v for v in row["features"]], dtype=np.float64)
        if i == 0:
            x[:] = np.nan  # all missing: pure imputation
        xi = impute(x[None, :], means).astype(np.float32)
        raw = float(onnx_predict(result.onnx, xi)[0])
        profile = PROFILES[i % len(PROFILES)]
        covered = profile.split(".")[0] in m["games"]
        calibrated = float(lookup(profile, glob, table).apply(np.array([raw]))[0]) if covered else None
        cases.append(
            {
                "profile": profile,
                "features": [None if not np.isfinite(v) else float(np.float32(v)) for v in x],
                "raw": raw if covered else None,
                "calibrated": calibrated,
            }
        )
    rng.shuffle(cases)
    expected = {"note": "Generated by python -m lookback_ml.make_fixture; do not edit by hand.", "tolerance": 1e-5, "cases": cases}
    (out / "expected.json").write_text(json.dumps(expected, indent=2) + "\n", encoding="utf-8", newline="\n")
    return expected


def main(argv: list[str] | None = None) -> int:
    import tempfile

    ap = argparse.ArgumentParser(prog="python -m lookback_ml.make_fixture", description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=FIXTURE)
    args = ap.parse_args(argv)
    with tempfile.TemporaryDirectory() as tmp:
        expected = build(Path(tmp), args.out)
    print(f"wrote {args.out} ({len(expected['cases'])} cases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
